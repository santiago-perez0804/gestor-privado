// Esquema base de Postgres (Supabase / PGlite): el mismo modelo que tenía SQLite al momento de la
// mudanza (incluye las columnas que fueron agregando las migraciones viejas). Los nombres van sin
// comillas, así Postgres los guarda en minúscula y la capa de datos (pg.js) los devuelve en camelCase.
// Fechas como texto ISO, JSON como texto y booleanos como INTEGER 0/1, igual que antes: no cambia
// ningún comportamiento.
export const BASE_SCHEMA = `
CREATE TABLE IF NOT EXISTS settings (
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS weights (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  weight DOUBLE PRECISION NOT NULL,
  recordedAt TEXT NOT NULL,
  createdAt TEXT NOT NULL,
  note TEXT
);

CREATE TABLE IF NOT EXISTS plans (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  description TEXT,
  icon TEXT,
  createdAt TEXT NOT NULL,
  updatedAt TEXT NOT NULL,
  goal TEXT,
  startDate TEXT,
  weeks INTEGER,
  deloadWeek INTEGER,
  progressionRule TEXT NOT NULL DEFAULT 'double_progression',
  priorityMuscles TEXT NOT NULL DEFAULT '[]',
  dailyExtras TEXT NOT NULL DEFAULT '[]',
  isActive INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS exercise_library (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  force TEXT,
  level TEXT,
  mechanic TEXT,
  equipment TEXT,
  primaryMuscles TEXT NOT NULL,
  secondaryMuscles TEXT NOT NULL,
  instructions TEXT NOT NULL,
  category TEXT,
  images TEXT
);

CREATE TABLE IF NOT EXISTS routines (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  planId INTEGER NOT NULL REFERENCES plans(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  description TEXT,
  icon TEXT,
  sortOrder INTEGER NOT NULL DEFAULT 0,
  createdAt TEXT NOT NULL,
  updatedAt TEXT NOT NULL,
  color TEXT
);

CREATE TABLE IF NOT EXISTS exercises (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  equipment TEXT NOT NULL DEFAULT 'otro' CHECK(equipment IN ('barra','mancuernas','polea','maquina','peso_corporal','otro')),
  bar TEXT CHECK(bar IS NULL OR bar IN ('olimpica','z')),
  isBodyweight INTEGER NOT NULL DEFAULT 0,
  muscles TEXT NOT NULL DEFAULT '[]',
  notes TEXT,
  isCustom INTEGER NOT NULL DEFAULT 0,
  sourceLibraryId TEXT,
  archived INTEGER NOT NULL DEFAULT 0,
  createdAt TEXT NOT NULL,
  updatedAt TEXT NOT NULL,
  kind TEXT NOT NULL DEFAULT 'strength' CHECK(kind IN ('strength','cardio')),
  cardioFields TEXT NOT NULL DEFAULT '[]',
  levelLabel TEXT,
  countLabel TEXT
);

CREATE TABLE IF NOT EXISTS routine_exercises (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  routineId INTEGER NOT NULL REFERENCES routines(id) ON DELETE CASCADE,
  exerciseId INTEGER NOT NULL REFERENCES exercises(id),
  sortOrder INTEGER NOT NULL DEFAULT 0,
  sets INTEGER NOT NULL DEFAULT 3 CHECK(sets BETWEEN 1 AND 20),
  repMin INTEGER NOT NULL DEFAULT 8 CHECK(repMin BETWEEN 1 AND 100),
  repMax INTEGER NOT NULL DEFAULT 12 CHECK(repMax >= repMin AND repMax <= 100),
  restSeconds INTEGER NOT NULL DEFAULT 120 CHECK(restSeconds BETWEEN 0 AND 1800),
  rirMin DOUBLE PRECISION,
  rirMax DOUBLE PRECISION,
  supersetGroup TEXT,
  notes TEXT,
  createdAt TEXT NOT NULL,
  updatedAt TEXT NOT NULL,
  targetMinutes INTEGER CHECK(targetMinutes IS NULL OR targetMinutes BETWEEN 1 AND 600)
);

CREATE TABLE IF NOT EXISTS exercise_logs (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  exerciseLibraryId TEXT NOT NULL REFERENCES exercise_library(id),
  routineId INTEGER REFERENCES routines(id) ON DELETE SET NULL,
  recordedAt TEXT NOT NULL,
  weight DOUBLE PRECISION,
  sets INTEGER NOT NULL,
  reps INTEGER NOT NULL,
  notes TEXT,
  createdAt TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS body_measurements (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type TEXT NOT NULL CHECK(type IN ('cintura','brazo','pecho','muslo','cuello','cadera')),
  value DOUBLE PRECISION NOT NULL,
  date TEXT NOT NULL,
  notes TEXT,
  createdAt TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS progress_photos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  date TEXT NOT NULL,
  fileName TEXT NOT NULL,
  notes TEXT,
  createdAt TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS plan_schedule (
  planId INTEGER NOT NULL REFERENCES plans(id) ON DELETE CASCADE,
  weekday INTEGER NOT NULL CHECK(weekday BETWEEN 1 AND 7),
  routineId INTEGER REFERENCES routines(id) ON DELETE SET NULL,
  extras TEXT NOT NULL DEFAULT '[]',
  PRIMARY KEY (planId, weekday)
);

CREATE TABLE IF NOT EXISTS workout_sessions (
  id TEXT PRIMARY KEY,
  planId INTEGER REFERENCES plans(id) ON DELETE SET NULL,
  routineId INTEGER REFERENCES routines(id) ON DELETE SET NULL,
  title TEXT NOT NULL,
  startedAt TEXT NOT NULL,
  endedAt TEXT,
  status TEXT NOT NULL DEFAULT 'in_progress' CHECK(status IN ('in_progress','done','discarded')),
  localDate TEXT NOT NULL,
  bodyweightKg DOUBLE PRECISION,
  notes TEXT,
  createdAt TEXT NOT NULL,
  updatedAt TEXT NOT NULL,
  kind TEXT NOT NULL DEFAULT 'strength' CHECK(kind IN ('strength','cardio'))
);

CREATE TABLE IF NOT EXISTS set_logs (
  id TEXT PRIMARY KEY,
  sessionId TEXT NOT NULL REFERENCES workout_sessions(id) ON DELETE CASCADE,
  exerciseId INTEGER NOT NULL REFERENCES exercises(id),
  exerciseOrder INTEGER NOT NULL,
  setOrder INTEGER NOT NULL,
  type TEXT NOT NULL DEFAULT 'working' CHECK(type IN ('warmup','working','drop','failure')),
  weightKg DOUBLE PRECISION,
  reps INTEGER CHECK(reps IS NULL OR reps BETWEEN 0 AND 200),
  rir DOUBLE PRECISION,
  completedAt TEXT,
  updatedAt TEXT NOT NULL,
  durationSeconds INTEGER CHECK(durationSeconds IS NULL OR durationSeconds BETWEEN 0 AND 86400),
  distanceKm DOUBLE PRECISION CHECK(distanceKm IS NULL OR distanceKm BETWEEN 0 AND 1000),
  level DOUBLE PRECISION,
  count INTEGER CHECK(count IS NULL OR count BETWEEN 0 AND 1000000)
);

CREATE TABLE IF NOT EXISTS goals (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type TEXT NOT NULL CHECK(type IN ('weight')),
  target DOUBLE PRECISION NOT NULL,
  targetDate TEXT,
  achievedAt TEXT,
  createdAt TEXT NOT NULL,
  updatedAt TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS measurement_sessions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  measuredOn TEXT NOT NULL,
  notes TEXT,
  createdAt TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS measurements (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sessionId INTEGER NOT NULL REFERENCES measurement_sessions(id) ON DELETE CASCADE,
  measuredOn TEXT NOT NULL,
  zone TEXT NOT NULL,
  valueCm DOUBLE PRECISION NOT NULL CHECK(valueCm > 0 AND valueCm < 400),
  legacyId INTEGER UNIQUE,
  createdAt TEXT NOT NULL,
  UNIQUE (sessionId, zone)
);

CREATE TABLE IF NOT EXISTS photo_sessions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  date TEXT NOT NULL,
  note TEXT,
  createdAt TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS photos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sessionId INTEGER NOT NULL REFERENCES photo_sessions(id) ON DELETE CASCADE,
  pose TEXT NOT NULL DEFAULT 'front' CHECK(pose IN ('front','side','back')),
  variant TEXT NOT NULL DEFAULT 'relaxed' CHECK(variant IN ('relaxed','flexed')),
  fileKey TEXT NOT NULL UNIQUE,
  thumbKey TEXT,
  mime TEXT,
  width INTEGER,
  height INTEGER,
  note TEXT,
  legacyId INTEGER UNIQUE,
  createdAt TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS habits (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  targetLabel TEXT,
  sortOrder INTEGER NOT NULL DEFAULT 0,
  archived INTEGER NOT NULL DEFAULT 0,
  createdAt TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS habit_logs (
  habitId INTEGER NOT NULL REFERENCES habits(id) ON DELETE CASCADE,
  localDate TEXT NOT NULL,
  done INTEGER NOT NULL DEFAULT 1,
  PRIMARY KEY (habitId, localDate)
);

CREATE TABLE IF NOT EXISTS recurring_expenses (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  description TEXT,
  amount DOUBLE PRECISION NOT NULL,
  currency TEXT NOT NULL DEFAULT 'ARS' CHECK(currency IN ('ARS','USD')),
  category TEXT,
  icon TEXT,
  dayOfMonth INTEGER NOT NULL CHECK(dayOfMonth BETWEEN 1 AND 28),
  active INTEGER NOT NULL DEFAULT 1,
  lastGeneratedBillingMonthKey TEXT,
  createdAt TEXT NOT NULL,
  updatedAt TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS expenses (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  description TEXT,
  amount DOUBLE PRECISION NOT NULL,
  currency TEXT NOT NULL DEFAULT 'ARS' CHECK(currency IN ('ARS','USD')),
  originalAmount DOUBLE PRECISION NOT NULL,
  exchangeRate DOUBLE PRECISION,
  installments INTEGER NOT NULL DEFAULT 1,
  date TEXT NOT NULL,
  icon TEXT,
  createdAt TEXT NOT NULL,
  updatedAt TEXT NOT NULL,
  category TEXT,
  recurringExpenseId INTEGER REFERENCES recurring_expenses(id) ON DELETE SET NULL,
  paymentMethod TEXT CHECK(paymentMethod IN ('credito','debito')),
  merchantType TEXT
);

CREATE TABLE IF NOT EXISTS budgets (
  category TEXT PRIMARY KEY,
  monthlyLimit DOUBLE PRECISION NOT NULL,
  rollover INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS incomes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  amount DOUBLE PRECISION NOT NULL,
  currency TEXT NOT NULL DEFAULT 'ARS' CHECK(currency IN ('ARS','USD')),
  originalAmount DOUBLE PRECISION NOT NULL,
  exchangeRate DOUBLE PRECISION,
  category TEXT NOT NULL DEFAULT 'sueldo',
  date TEXT NOT NULL,
  notes TEXT,
  createdAt TEXT NOT NULL,
  updatedAt TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS savings_goals (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  targetAmount DOUBLE PRECISION NOT NULL,
  currency TEXT NOT NULL DEFAULT 'ARS' CHECK(currency IN ('ARS','USD')),
  deadline TEXT,
  icon TEXT,
  archived INTEGER NOT NULL DEFAULT 0,
  createdAt TEXT NOT NULL,
  updatedAt TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS savings_contributions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  goalId INTEGER NOT NULL REFERENCES savings_goals(id) ON DELETE CASCADE,
  amount DOUBLE PRECISION NOT NULL,
  date TEXT NOT NULL,
  note TEXT,
  createdAt TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS recurring_incomes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  amount DOUBLE PRECISION NOT NULL,
  currency TEXT NOT NULL DEFAULT 'ARS' CHECK(currency IN ('ARS','USD')),
  category TEXT NOT NULL DEFAULT 'sueldo',
  dayOfMonth INTEGER NOT NULL CHECK(dayOfMonth BETWEEN 1 AND 28),
  active INTEGER NOT NULL DEFAULT 1,
  lastGeneratedBillingMonthKey TEXT,
  createdAt TEXT NOT NULL,
  updatedAt TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS accounts (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  type TEXT NOT NULL DEFAULT 'banco' CHECK(type IN ('efectivo','banco','billetera','inversion','otro')),
  currency TEXT NOT NULL DEFAULT 'ARS' CHECK(currency IN ('ARS','USD')),
  balance DOUBLE PRECISION NOT NULL DEFAULT 0,
  archived INTEGER NOT NULL DEFAULT 0,
  createdAt TEXT NOT NULL,
  updatedAt TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS account_snapshots (
  accountId INTEGER NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
  date TEXT NOT NULL,
  balance DOUBLE PRECISION NOT NULL,
  PRIMARY KEY (accountId, date)
);

CREATE TABLE IF NOT EXISTS debts (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  person TEXT,
  direction TEXT NOT NULL DEFAULT 'debo' CHECK(direction IN ('debo','me_deben')),
  amount DOUBLE PRECISION NOT NULL,
  paidAmount DOUBLE PRECISION NOT NULL DEFAULT 0,
  currency TEXT NOT NULL DEFAULT 'ARS' CHECK(currency IN ('ARS','USD')),
  dueDate TEXT,
  notes TEXT,
  settledAt TEXT,
  createdAt TEXT NOT NULL,
  updatedAt TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS media_items (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type TEXT NOT NULL CHECK(type IN ('pelicula','serie','libro','videojuego')),
  title TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'pendiente' CHECK(status IN ('pendiente','en_progreso','completado','abandonado')),
  rating INTEGER CHECK(rating BETWEEN 1 AND 5),
  notes TEXT,
  startedAt TEXT,
  finishedAt TEXT,
  progressCurrent INTEGER,
  progressTotal INTEGER,
  progressLabel TEXT,
  icon TEXT,
  createdAt TEXT NOT NULL,
  updatedAt TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS works (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type TEXT NOT NULL CHECK(type IN ('movie','series','book','game')),
  title TEXT NOT NULL,
  originalTitle TEXT,
  creators TEXT NOT NULL DEFAULT '[]',
  year INTEGER,
  genres TEXT NOT NULL DEFAULT '[]',
  coverUrl TEXT,
  coverPath TEXT,
  externalSource TEXT,
  externalId TEXT,
  metadata TEXT NOT NULL DEFAULT '{}',
  createdAt TEXT NOT NULL,
  updatedAt TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS library_entries (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workId INTEGER NOT NULL UNIQUE REFERENCES works(id) ON DELETE CASCADE,
  status TEXT NOT NULL DEFAULT 'want' CHECK(status IN ('want','in_progress','done','dropped')),
  rating DOUBLE PRECISION CHECK(rating IS NULL OR (rating BETWEEN 0.5 AND 5 AND rating * 2 = floor(rating * 2))),
  priority INTEGER CHECK(priority IS NULL OR priority BETWEEN 1 AND 3),
  recommendedBy TEXT,
  format TEXT,
  notes TEXT,
  legacyMediaItemId INTEGER UNIQUE,
  createdAt TEXT NOT NULL,
  updatedAt TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS passes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entryId INTEGER NOT NULL REFERENCES library_entries(id) ON DELETE CASCADE,
  number INTEGER NOT NULL DEFAULT 1,
  status TEXT NOT NULL DEFAULT 'in_progress' CHECK(status IN ('in_progress','done','dropped')),
  startedAt TEXT,
  finishedAt TEXT,
  progress TEXT NOT NULL DEFAULT '{}',
  dropReason TEXT,
  createdAt TEXT NOT NULL,
  updatedAt TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS reviews (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entryId INTEGER NOT NULL REFERENCES library_entries(id) ON DELETE CASCADE,
  passId INTEGER REFERENCES passes(id) ON DELETE SET NULL,
  text TEXT NOT NULL,
  hasSpoilers INTEGER NOT NULL DEFAULT 0,
  createdAt TEXT NOT NULL,
  updatedAt TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS highlights (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workId INTEGER NOT NULL REFERENCES works(id) ON DELETE CASCADE,
  text TEXT NOT NULL,
  location TEXT,
  note TEXT,
  source TEXT NOT NULL DEFAULT 'manual',
  createdAt TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS reading_sessions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workId INTEGER NOT NULL REFERENCES works(id) ON DELETE CASCADE,
  startTime TEXT NOT NULL,
  durationSeconds INTEGER NOT NULL,
  pagesRead INTEGER NOT NULL DEFAULT 0,
  source TEXT NOT NULL DEFAULT 'manual' CHECK(source IN ('koreader','manual')),
  externalKey TEXT UNIQUE,
  createdAt TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS koreader_books (
  key TEXT PRIMARY KEY,
  title TEXT,
  authors TEXT,
  pages INTEGER,
  workId INTEGER REFERENCES works(id) ON DELETE SET NULL,
  lastImportedAt TEXT,
  ignored INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS artworks (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  technique TEXT,
  sizeLabel TEXT,
  createdOn TEXT,
  description TEXT,
  inventoryCode TEXT UNIQUE,
  imagePath TEXT NOT NULL,
  thumbPath TEXT,
  width INTEGER,
  height INTEGER,
  mime TEXT,
  isFavorite INTEGER NOT NULL DEFAULT 0,
  showOnEasel INTEGER NOT NULL DEFAULT 1,
  createdAt TEXT NOT NULL,
  updatedAt TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS ocio_goals (
  year INTEGER NOT NULL,
  type TEXT NOT NULL CHECK(type IN ('movie','series','book','game','outing')),
  target INTEGER NOT NULL CHECK(target > 0),
  PRIMARY KEY (year, type)
);

CREATE TABLE IF NOT EXISTS catalog_cache (
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL,
  fetchedAt TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS google_account (
  id INTEGER PRIMARY KEY CHECK(id = 1),
  refreshTokenEnc TEXT,
  email TEXT,
  calendarId TEXT,
  calendarName TEXT,
  syncToken TEXT,
  lastSyncAt TEXT,
  lastError TEXT,
  status TEXT NOT NULL DEFAULT 'disconnected' CHECK(status IN ('disconnected','connected','revoked','error')),
  updatedAt TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS google_sync_log (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  at TEXT NOT NULL,
  kind TEXT NOT NULL CHECK(kind IN ('conflict','error','info')),
  message TEXT NOT NULL,
  outingId INTEGER
);

CREATE TABLE IF NOT EXISTS outings (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  category TEXT,
  date TEXT NOT NULL,
  startTime TEXT,
  endTime TEXT,
  allDay INTEGER NOT NULL DEFAULT 1,
  place TEXT,
  withWhom TEXT,
  notes TEXT,
  status TEXT NOT NULL DEFAULT 'tentative' CHECK(status IN ('tentative','confirmed','attended','not_attended')),
  icon TEXT,
  source TEXT NOT NULL DEFAULT 'app' CHECK(source IN ('app','google')),
  googleEventId TEXT UNIQUE,
  googleEtag TEXT,
  googleUpdated TEXT,
  deletedAt TEXT,
  createdAt TEXT NOT NULL,
  updatedAt TEXT NOT NULL,
  googleSyncedAt TEXT
);

CREATE TABLE IF NOT EXISTS projects (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  description TEXT,
  type TEXT NOT NULL DEFAULT 'instagram' CHECK(type IN ('instagram')),
  icon TEXT,
  url TEXT,
  igUserId TEXT,
  igUsername TEXT,
  igProfilePictureUrl TEXT,
  accessToken TEXT,
  tokenIssuedAt TEXT,
  tokenExpiresAt TEXT,
  lastSyncAt TEXT,
  lastSyncError TEXT,
  createdAt TEXT NOT NULL,
  updatedAt TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS project_snapshots (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  projectId INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  date TEXT NOT NULL,
  followers INTEGER,
  follows INTEGER,
  mediaCount INTEGER,
  reach INTEGER,
  views INTEGER,
  profileViews INTEGER,
  accountsEngaged INTEGER,
  createdAt TEXT NOT NULL,
  updatedAt TEXT NOT NULL,
  UNIQUE(projectId, date)
);

CREATE TABLE IF NOT EXISTS certificates (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  issuer TEXT,
  issuedAt TEXT,
  expiresAt TEXT,
  hours DOUBLE PRECISION,
  credentialId TEXT,
  verifyUrl TEXT,
  skills TEXT,
  notes TEXT,
  fileName TEXT,
  mimeType TEXT,
  createdAt TEXT NOT NULL,
  updatedAt TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS outing_expenses (
  outingId INTEGER NOT NULL REFERENCES outings(id) ON DELETE CASCADE,
  expenseId INTEGER NOT NULL REFERENCES expenses(id) ON DELETE CASCADE,
  createdAt TEXT NOT NULL,
  PRIMARY KEY (outingId, expenseId)
);

CREATE TABLE IF NOT EXISTS dropbox_account (
  id INTEGER PRIMARY KEY CHECK(id = 1),
  refreshTokenEnc TEXT,
  email TEXT,
  path TEXT NOT NULL DEFAULT '/statistics.sqlite3',
  lastRev TEXT,
  lastSyncAt TEXT,
  lastCheckAt TEXT,
  lastError TEXT,
  lastSummary TEXT,
  status TEXT NOT NULL DEFAULT 'disconnected' CHECK(status IN ('disconnected','connected','revoked','error')),
  updatedAt TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_weights_recordedAt ON weights(recordedAt);
CREATE UNIQUE INDEX IF NOT EXISTS idx_exercises_name ON exercises(lower(name));
CREATE INDEX IF NOT EXISTS idx_workout_sessions_date ON workout_sessions(localDate);
CREATE INDEX IF NOT EXISTS idx_workout_sessions_status ON workout_sessions(status);
CREATE INDEX IF NOT EXISTS idx_set_logs_session ON set_logs(sessionId);
CREATE INDEX IF NOT EXISTS idx_set_logs_exercise ON set_logs(exerciseId, completedAt);
CREATE INDEX IF NOT EXISTS idx_measurements_zone ON measurements(zone, measuredOn);
CREATE INDEX IF NOT EXISTS idx_photos_session ON photos(sessionId);
CREATE INDEX IF NOT EXISTS idx_routines_planId ON routines(planId);
CREATE INDEX IF NOT EXISTS idx_routine_exercises_routineId ON routine_exercises(routineId);
CREATE INDEX IF NOT EXISTS idx_exercise_logs_exerciseLibraryId ON exercise_logs(exerciseLibraryId);
CREATE INDEX IF NOT EXISTS idx_exercise_logs_recordedAt ON exercise_logs(recordedAt);
CREATE INDEX IF NOT EXISTS idx_exercise_library_equipment ON exercise_library(equipment);
CREATE INDEX IF NOT EXISTS idx_body_measurements_type_date ON body_measurements(type, date);
CREATE INDEX IF NOT EXISTS idx_progress_photos_date ON progress_photos(date);
CREATE INDEX IF NOT EXISTS idx_expenses_date ON expenses(date);
CREATE INDEX IF NOT EXISTS idx_incomes_date ON incomes(date);
CREATE INDEX IF NOT EXISTS idx_savings_contributions_goalId ON savings_contributions(goalId);
CREATE INDEX IF NOT EXISTS idx_recurring_expenses_active ON recurring_expenses(active);
CREATE UNIQUE INDEX IF NOT EXISTS ux_works_external ON works(externalSource, externalId) WHERE externalId IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_works_type ON works(type);
CREATE INDEX IF NOT EXISTS idx_library_entries_status ON library_entries(status);
CREATE INDEX IF NOT EXISTS idx_passes_entry ON passes(entryId);
CREATE INDEX IF NOT EXISTS idx_passes_finishedAt ON passes(finishedAt);
CREATE INDEX IF NOT EXISTS idx_reviews_entry ON reviews(entryId);
CREATE INDEX IF NOT EXISTS idx_highlights_work ON highlights(workId);
CREATE INDEX IF NOT EXISTS idx_reading_sessions_work ON reading_sessions(workId, startTime);
CREATE INDEX IF NOT EXISTS idx_reading_sessions_start ON reading_sessions(startTime);
CREATE INDEX IF NOT EXISTS idx_project_snapshots_project_date ON project_snapshots(projectId, date);
CREATE INDEX IF NOT EXISTS idx_certificates_issuedAt ON certificates(issuedAt);
CREATE INDEX IF NOT EXISTS idx_expenses_category ON expenses(category);
CREATE INDEX IF NOT EXISTS idx_expenses_recurringExpenseId ON expenses(recurringExpenseId);
CREATE INDEX IF NOT EXISTS idx_outings_date ON outings(date);
CREATE INDEX IF NOT EXISTS idx_outings_status ON outings(status);
CREATE INDEX IF NOT EXISTS idx_outing_expenses_expense ON outing_expenses(expenseId);
CREATE INDEX IF NOT EXISTS idx_routine_exercises_exercise ON routine_exercises(exerciseId);
`;
